"""Generate DOCS/RULES.md from the built-in rule files.

    python scripts/generate_rules_doc.py          # rewrite DOCS/RULES.md
    python scripts/generate_rules_doc.py --check  # exit 1 if DOCS/RULES.md is stale

tests/unit/test_rules_doc.py runs the check, so the catalog can't drift from the YAML.
"""

from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = ROOT / "src" / "tmac" / "rules"
DOC = ROOT / "DOCS" / "RULES.md"
SEVERITIES = ["Critical", "High", "Medium", "Low", "Info"]


def _load(subdir: str) -> list[dict]:
    rules: dict[str, dict] = {}
    for path in sorted((RULES_DIR / subdir).glob("threats*.yaml")):
        for rule in yaml.safe_load(path.read_text(encoding="utf-8"))["rules"]:
            rules[rule["id"]] = rule  # same override order as RuleLoader
    return list(rules.values())


def _service(rule_id: str) -> str:
    return rule_id.split("-")[2]


def _cell(text: object) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render() -> str:
    tf, cfn = _load("aws"), _load("cfn")
    by_service: dict[str, list[dict]] = defaultdict(list)
    for rule in tf:
        by_service[_service(rule["id"])].append(rule)
    types = {r["resource_type"] for r in tf}
    sev_tf, sev_cfn = Counter(r["severity"] for r in tf), Counter(r["severity"] for r in cfn)

    out = [
        "# Rule Catalog — TMAC",
        "",
        "<!-- Generated by scripts/generate_rules_doc.py — do not edit by hand. -->",
        "",
        (
            f"TMAC includes **{len(tf):,} Terraform rules** covering **{len(types)} AWS resource "
            f"types** across **{len(by_service)} services** (`TMAC-AWS-{{SERVICE}}-{{NNN}}`, used by "
            f"`tmac scan`, `tmac plan` and `tmac ci`), plus **{len(cfn)} CloudFormation rules** "
            "(`TMAC-CFN-{SERVICE}-{NNN}`, used by `tmac cfn`)."
        ),
        "",
        "## Summary by severity",
        "",
        "| Severity | Terraform | CloudFormation |",
        "| :--- | :--- | :--- |",
        *(f"| {s} | {sev_tf[s]} | {sev_cfn[s]} |" for s in SEVERITIES),
        f"| **Total** | **{len(tf):,}** | **{len(cfn)}** |",
        "",
        "## CloudFormation rules (`tmac cfn`)",
        "",
        "Defined in [`src/tmac/rules/cfn/threats.yaml`](../src/tmac/rules/cfn/threats.yaml), with a",
        "CloudFormation ↔ Terraform type mapping in its `metadata`. They apply only to `AWS::*`",
        "resource types, so they never affect `tmac scan`.",
        "",
        "| ID | Resource type | Name | Severity | STRIDE |",
        "| :--- | :--- | :--- | :--- | :--- |",
        *(
            f"| `{r['id']}` | `{r['resource_type']}` | {_cell(r['name'])} | {r['severity']} "
            f"| {r['stride']} |"
            for r in cfn
        ),
        "",
        "## Rules by service",
        "",
        "| Service | Rules | Resource types |",
        "| :--- | :--- | :--- |",
    ]
    for service, rules in sorted(by_service.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        rtypes = ", ".join(f"`{t}`" for t in sorted({r["resource_type"] for r in rules}))
        out.append(f"| {service} | {len(rules)} | {rtypes} |")
    out += ["", "## Rule detail", ""]
    for service in sorted(by_service):
        out += [
            f"### {service}",
            "",
            "| ID | Name | Severity | STRIDE |",
            "| :--- | :--- | :--- | :--- |",
        ]
        out += [
            f"| `{r['id']}` | {_cell(r['name'])} | {r['severity']} | {r['stride']} |"
            for r in sorted(by_service[service], key=lambda r: r["id"])
        ]
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        current = DOC.read_text(encoding="utf-8").replace("\r\n", "\n") if DOC.exists() else ""
        if current != content:
            print(f"{DOC} is out of date; run: python scripts/generate_rules_doc.py")
            return 1
        return 0
    DOC.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
